-- ============================================================
--  Моя кондитерская — схема базы для Supabase.
--  Запустить ОДИН раз: Supabase → SQL Editor → New query → вставить
--  весь файл → Run. Повторный запуск безопасен.
--
--  Кто что может:
--    • покупатель (без входа) — только оформить заказ (place_order)
--      и посмотреть СВОИ заказы по секретному ключу из своего браузера (my_orders);
--      читать или менять таблицу напрямую не может;
--    • владелец (вход по почте и паролю + запись в owners) — видит все
--      заказы, имена и телефоны, меняет статусы.
-- ============================================================

-- ── заказы ──────────────────────────────────────────────────
create table if not exists public.orders (
  id              bigint generated by default as identity (start with 1051) primary key,  -- номер заказа
  created_at      timestamptz not null default now(),
  receive_at      timestamptz,                                    -- когда покупатель хочет получить
  delivery        text not null check (delivery in ('pickup', 'delivery')),
  items           jsonb not null check (jsonb_typeof(items) = 'array'),   -- [{id, name, w, qty, price, note}]
  total           integer not null check (total >= 0 and total < 10000000),
  customer_name   text check (char_length(customer_name)  <= 80),
  customer_phone  text check (char_length(customer_phone) <= 40),
  address         jsonb,                                          -- только при доставке
  status          text not null default 'new' check (status in ('new', 'ready', 'done', 'cancel')),
  status_at       timestamptz not null default now(),
  token           uuid not null default gen_random_uuid()         -- секрет покупателя для «Моих заказов»
);
create index if not exists orders_status_idx  on public.orders (status);
create index if not exists orders_created_idx on public.orders (created_at desc);
create index if not exists orders_token_idx   on public.orders (token);

alter table public.orders enable row level security;

-- ── владельцы ───────────────────────────────────────────────
create table if not exists public.owners (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.owners enable row level security;

drop policy if exists "owner sees self" on public.owners;
create policy "owner sees self" on public.owners
  for select to authenticated using (user_id = auth.uid());

create or replace function public.is_owner()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.owners where user_id = auth.uid());
$$;

-- владелец читает и меняет заказы; у остальных прямого доступа к таблице нет
drop policy if exists "owner reads orders"   on public.orders;
drop policy if exists "owner updates orders" on public.orders;
create policy "owner reads orders"   on public.orders for select to authenticated using (public.is_owner());
create policy "owner updates orders" on public.orders for update to authenticated
  using (public.is_owner()) with check (public.is_owner());

-- статус меняется — время смены ставится само
create or replace function public.touch_status()
returns trigger language plpgsql as $$
begin
  if new.status is distinct from old.status then new.status_at := now(); end if;
  return new;
end $$;
drop trigger if exists orders_touch_status on public.orders;
create trigger orders_touch_status before update on public.orders
  for each row execute function public.touch_status();

-- ── оформить заказ (покупатель, без входа) ──────────────────
create or replace function public.place_order(
  p_items jsonb, p_total integer, p_delivery text, p_receive_at timestamptz,
  p_name text, p_phone text, p_address jsonb
) returns table (order_no bigint, order_token uuid)
language plpgsql security definer set search_path = public as $$
begin
  if p_delivery not in ('pickup', 'delivery') then raise exception 'delivery'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 30 then raise exception 'items'; end if;
  if coalesce(btrim(p_name), '') = '' or coalesce(btrim(p_phone), '') = '' then raise exception 'contacts'; end if;
  if p_total is null or p_total < 0 or p_total >= 10000000 then raise exception 'total'; end if;

  return query
    insert into public.orders (items, total, delivery, receive_at, customer_name, customer_phone, address)
    values (p_items, p_total, p_delivery, p_receive_at,
            left(btrim(p_name), 80), left(btrim(p_phone), 40),
            case when p_delivery = 'delivery' then p_address end)
    returning orders.id, orders.token;
end $$;

-- ── мои заказы: только по секретам из браузера покупателя, без имён и телефонов ──
create or replace function public.my_orders(p_tokens uuid[])
returns table (order_no bigint, created_at timestamptz, receive_at timestamptz, delivery text,
               items jsonb, total integer, status text, status_at timestamptz)
language sql stable security definer set search_path = public as $$
  select o.id, o.created_at, o.receive_at, o.delivery, o.items, o.total, o.status, o.status_at
  from public.orders o
  where o.token = any (p_tokens[1:50])
  order by o.id desc;
$$;

-- функции доступны сайту; таблицы напрямую — нет
revoke all on function public.place_order(jsonb, integer, text, timestamptz, text, text, jsonb) from public;
revoke all on function public.my_orders(uuid[]) from public;
grant execute on function public.place_order(jsonb, integer, text, timestamptz, text, text, jsonb) to anon, authenticated;
grant execute on function public.my_orders(uuid[]) to anon, authenticated;
grant execute on function public.is_owner() to authenticated;

